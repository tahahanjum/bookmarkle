  const TABLES = { en, de, nl, fr, es, pt, it, pl, tr, ru, ja, ko, zh, hi, id, vi, ar };

  function resolve(setting) {
    if (setting && setting !== 'auto') {
      return TABLES[setting] ? setting : 'en';
    }
    const nav = (global.navigator?.language || 'en').slice(0, 2).toLowerCase();
    return TABLES[nav] ? nav : 'en';
  }

  let current = 'en';

  global.I18n = {
    setLanguage(setting) { current = resolve(setting); return current; },
    current() { return current; },

    t(key, vars) {
      let s = TABLES[current]?.[key] ?? en[key] ?? key;
      if (vars) {
        Object.keys(vars).forEach(k => { s = s.split(`{${k}}`).join(vars[k]); });
      }
      return s;
    },
    has(code) { return !!TABLES[code]; },
    codes() { return Object.keys(TABLES); }
  };
